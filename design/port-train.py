"""Port design/p3-train-bg.html into the skin: src/client/p3r/train.ts + src/client/p3r/train.css.

    python -I design/port-train.py

The design page stays the source of truth for the night-train background; rerun after editing it.
"""
import re
from pathlib import Path

here = Path(__file__).resolve().parent
src = (here / 'p3-train-bg.html').read_text(encoding='utf-8')
out_dir = here.parent / 'src' / 'client' / 'p3r'

# ------------------------------------------------------------------ CSS
css = src[src.index('<style>') + 7: src.index('</style>')]
keep = []
for block in re.findall(r'(@keyframes[^{]+\{(?:[^{}]*\{[^}]*\})*[^}]*\}|@media[^{]+\{(?:[^{}]*\{[^}]*\})*[^}]*\}|[^{}@]+\{[^}]*\})', css):
    b = block.strip()
    if b.startswith('@keyframes'):
        keep.append(b)
        continue
    if b.startswith('@media'):
        if 'prefers-reduced-motion' in b:
            keep.append('@media (prefers-reduced-motion: reduce) { .p3r-train *, .p3r-train *::before, .p3r-train *::after { animation: none !important; } }')
        continue
    sel, body = b.split('{', 1)
    sels = [s.strip() for s in sel.split(',')]
    out = []
    for s in sels:
        s = re.sub(r'/\*.*?\*/', '', s, flags=re.S).strip()
        if not s or s in ('html', 'body', '*', '#fit') or s.startswith(('.ghost', '.g-', '.ui ', '.ctl')):
            continue
        if s == ':root':
            s = '.stage'
        s = s.replace('#whaleCv', '.whalecv')
        out.append('.p3r-train ' + s)
    if out:
        keep.append(', '.join(out) + ' {' + body)
css = '\n'.join(keep)
names = sorted(set(re.findall(r'@keyframes\s+([\w-]+)', css)), key=len, reverse=True)
for n in names:
    css = re.sub(r'@keyframes\s+%s\b' % re.escape(n), '@keyframes p3r-' + n, css)
def rename(m):
    decl = m.group(0)
    for n in names:
        decl = re.sub(r'(?<![\w-])%s(?![\w-])' % re.escape(n), 'p3r-' + n, decl)
    return decl
css = re.sub(r'animation(?:-name)?\s*:[^;}]+', rename, css)
# the stage/fit wrappers
css = """/* Generated by design/port-train.py from design/p3-train-bg.html. Do not edit by hand. */
.p3r-train { position: absolute; inset: 0; overflow: hidden; pointer-events: none; contain: strict; }
.p3r-train .fit { position: absolute; left: 50%; top: 50%; width: 1920px; height: 1200px; transform-origin: 50% 50%; }
.p3r-train .stage { position: absolute; inset: 0; }
.p3r-train *, .p3r-train *::before, .p3r-train *::after { corner-shape: round; }
""" + css + '\n'
(out_dir / 'train.css').write_text(css, encoding='utf-8')

# ------------------------------------------------------------------ JS
js = src[src.index('<script>') + 8: src.rindex('</script>')]
def cut(a, b):
    i = js.index(a); j = js.index(b, i)
    return js[i:j]
scenes = cut("  const NAVY = ", "  $('#tower').innerHTML = TOWER;")
carriage = cut("  const rr = (x, y, w, h, r) =>", "  /* =====================================================================\n     DOT-MATRIX SEA")
sea = cut("  const HZ = 492", "  const reduce = matchMedia")
sea = sea.replace("$('#seaCv')", "q<HTMLCanvasElement>('.sea')")
# the page's own egg timer is replaced by the module's (cancellable) one
sea = re.sub(r"  let eggStart = null;\n  const summonWhale = .*?\n  const scheduleEgg = .*?\n", "", sea)
assert 'let eggStart' not in sea
for a, b in [("stage.classList", "stageEl.classList"), ("$('#ledtag')", "q('.led .tag')"), ("$('#ledtxt')", "q('.led .run span')")]:
    sea = sea.replace(a, b); carriage = carriage.replace(a, b)
carriage = carriage.replace("'<div class=\"tag\" id=\"ledtag\">快速</div><div class=\"run\"><span id=\"ledtxt\"></span></div>'", "'<div class=\"tag\">快速</div><div class=\"run\"><span></span></div>'")

ts = r'''// @ts-nocheck — generated by design/port-train.py from design/p3-train-bg.html (the design page is the source of truth).
/**
 * The P3R night-train background: a pseudo-3D carriage seen side-on, the
 * workspace's own scenery passing outside, a dot-matrix sea whose dots never
 * move (only breathe), and a dot-matrix whale that breaches as a rare egg.
 * Purely decorative: aria-hidden, no pointer events, no network.
 */
export interface Train {
  setWorkspace(name: string): void
  setDark(on: boolean): void
  summonWhale(): void
  pointer(nx: number, ny: number): void
  dispose(): void
}

export function mountTrain(host: HTMLElement, win: Window): Train {
  const doc = host.ownerDocument
  const root = doc.createElement('div')
  root.className = 'p3r-train'
  root.setAttribute('aria-hidden', 'true')
  root.innerHTML = `<div class="fit"><div class="stage">
    <div class="back"><div class="stars"></div><div class="moon"></div><div class="tower"></div><div class="hills"></div><canvas class="sea" width="1920" height="1200"></canvas></div>
    <div class="grade"></div><div class="grain"></div></div></div>`
  host.prepend(root)
  const q = <T extends Element = HTMLElement>(s: string) => root.querySelector(s) as T
  const fitEl = q('.fit'), stageEl = q('.stage'), gradeEl = q('.grade')
  let rock
  const layer = (rocking = false, cls = '') => { const r = doc.createElement('div'); r.className = 'room ' + cls; rock = doc.createElement('div'); rock.className = rocking ? 'rock' : 'lay'; r.appendChild(rock); stageEl.insertBefore(r, gradeEl); return r }
  const el = (cls, css = '', html = '') => { const d = doc.createElement('div'); d.className = cls; if (css) d.style.cssText = css; d.innerHTML = html; rock.appendChild(d); return d }
  const svgURI = s => `url("data:image/svg+xml,${encodeURIComponent(s)}")`
  const f = n => Math.round(n)
  const reduce = win.matchMedia('(prefers-reduced-motion: reduce)').matches

''' + scenes + r'''
  q('.tower').innerHTML = TOWER

  const cityRoom = layer(false, 'outside'); const cityEl = el('city', '', '<i></i>').firstChild
  const whaleCv = doc.createElement('canvas'); whaleCv.className = 'whalecv'; whaleCv.width = 1920; whaleCv.height = 1200; stageEl.insertBefore(whaleCv, gradeEl)
  layer(false, 'outside'); el('wires')
  layer(false, 'outside'); for (let i = 0; i < 3; i++) el('pole', '', `<i style="animation-delay:${-i * .8}s"></i>`)
  const tl = doc.createElement('div'); tl.className = 'tlights'; stageEl.insertBefore(tl, gradeEl)
  layer(true)
''' + carriage + sea + r'''
  let eggStart = null, eggTimer = 0, raf = 0, last = 0, disposed = false
  const summonWhale = () => { if (eggStart == null) eggStart = win.performance.now() / 1000 - .35 * CYCLE }
  const scheduleEgg = () => { eggTimer = win.setTimeout(() => { summonWhale(); scheduleEgg() }, (240 + Math.random() * 360) * 1000) }
  const frame = now => { if (disposed) return; if (!stageEl.classList.contains('paused') && now - last > 33) { draw(now); last = now } raf = win.requestAnimationFrame(frame) }

  /* --- workspace -> scenery; the LED board only names the workspace --- */
  const ORDER = ['bay', 'island', 'school', 'arcade', 'dorm']
  const sceneFor = ws => ORDER[[...ws].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7) % ORDER.length]
  const cache = {}
  let curWs = '', tunnelA = 0, tunnelB = 0
  const setLed = () => { const dark = stageEl.classList.contains('dark'), name = curWs || 'DSH'
    q('.led .tag').textContent = dark ? '影时' : '快速'
    const span = q('.led .run span'); span.textContent = dark ? `影时间 DARK HOUR 0:00　·　${name}　·　本列车不停靠任何站` : `次は ▶ ${name}　·　NEXT STOP: ${name.toUpperCase()}　·　${name}`
    const dur = (span.scrollWidth + 880) / 110; span.style.animationDuration = `${dur}s`; span.style.animationDelay = `${-dur * .3}s` }
  const applyScene = () => { const key = sceneFor(curWs || 'dsh'), sc = SCENES[key]
    cityEl.style.backgroundImage = cache[key] ||= sc.build()
    q('.hills').style.backgroundImage = backTile(sc.back)
    q('.tower').classList.toggle('far', sc.tower !== 'near'); setLed() }

  const fit = () => { const r = host.getBoundingClientRect(); const s = Math.max(r.width / 1920, r.height / 1200) || 1; fitEl.style.transform = `translate(-50%,-50%) scale(${s})` }
  const ro = new win.ResizeObserver(fit); ro.observe(host); fit()
  applyScene()
  draw(win.performance.now())
  if (!reduce) { raf = win.requestAnimationFrame(frame); scheduleEgg() }

  let ptr = null
  return {
    setWorkspace(name) {
      if (name === curWs) return
      const first = !curWs; curWs = name
      if (first || reduce) { applyScene(); return }
      win.clearTimeout(tunnelA); win.clearTimeout(tunnelB)
      stageEl.classList.add('tunnel'); tunnelA = win.setTimeout(applyScene, 380); tunnelB = win.setTimeout(() => stageEl.classList.remove('tunnel'), 900)
    },
    setDark(on) { if (stageEl.classList.contains('dark') === on) return; stageEl.classList.toggle('dark', on); setLed(); draw(win.performance.now()) },
    summonWhale,
    pointer(nx, ny) { if (reduce) return; const pending = ptr; ptr = [nx, ny]; if (pending) return
      win.requestAnimationFrame(() => { if (!ptr) return; const [x, y] = ptr; ptr = null; const st = stageEl.style
        st.setProperty('--ry', `${17 + x * 5}deg`); st.setProperty('--rx', `${-y * 2.5}deg`); st.setProperty('--tx', `${120 - x * 40}px`); st.setProperty('--mx', `${-x * 14}px`); st.setProperty('--my', `${-y * 8}px`) }) },
    dispose() { disposed = true; win.cancelAnimationFrame(raf); win.clearTimeout(eggTimer); win.clearTimeout(tunnelA); win.clearTimeout(tunnelB); ro.disconnect(); root.remove() },
  }
}
'''
# the sea's draw() uses `stage.classList` for the palette; reduce/__drawAt helpers were cut out above
(out_dir / 'train.ts').write_text(ts, encoding='utf-8')
print('train.ts', len(ts), 'train.css', len(css), 'keyframes', names)
